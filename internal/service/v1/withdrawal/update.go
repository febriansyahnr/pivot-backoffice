package withdrawalService

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/paper-indonesia/pivot-backoffice/constant"
	commonModel "github.com/paper-indonesia/pivot-backoffice/internal/model/common"
	routingProcessorModel "github.com/paper-indonesia/pivot-backoffice/internal/model/routingProcessor/bankTransfer"
	"github.com/paper-indonesia/pivot-backoffice/internal/model/withdrawal"
	"github.com/paper-indonesia/pivot-backoffice/pkg/util"

	"github.com/paper-indonesia/pdk/v2/logger"
)

func (s *withdrawalService) UpdateBankTransferStatus(ctx context.Context, request *routingProcessorModel.BankTransferResponseData) error {
	ctx, segment := otelTracer.Start(ctx, "internal/service/v1/withdrawal/UpdateBankTransferStatus")
	defer segment.End()

	// Transaction data is obtained from search results based on external ID
	// and is performed in the handler section to determine which use case to use.
	if request == nil || request.Transaction == nil {
		return nil
	}
	// The handling is done here because some use cases allow for status changes, for statuses that are already final.
	if request.Transaction.Status != constant.StatusPending {
		s.logger.Info(ctx, "Transaction status is final, status cannot be updated. Bank transfer status update ignored", logger.String("status", request.Transaction.Status))
		return nil
	}

	withdrawalDetail, err := s.repo.GetById(ctx, &withdrawal.WithdrawalDetailRequest{
		Id:          request.Transaction.ReferenceID,
		AccountName: request.Transaction.Reference,
		MerchantId:  request.Transaction.MerchantID.String(),
	})
	if err != nil {
		return fmt.Errorf("get withdrawal details: %v", err)

	} else if withdrawalDetail == nil {
		return errors.New("withdrawal detail not found")
	}

	if withdrawalDetail.RawMetadata.Valid {
		_ = withdrawalDetail.RawMetadata.Unmarshal(&withdrawalDetail.Metadata)
	}

	withdrawalDetail.Metadata.BankTransfer = &withdrawal.BankTransfer{
		UUID:               request.UUID,
		ExternalId:         request.ExternalID,
		BankReferenceNo:    request.BankReferenceNo,
		PartnerReferenceNo: request.PartnerReferenceNo,
	}

	updateAt := time.Now().UTC()
	if err = s.repo.UpdateMetadataById(ctx, withdrawalDetail.Id, &withdrawalDetail.Metadata); err != nil {
		return fmt.Errorf("update withdrawal metadata: %v", err)
	}

	if err = s.orchestratorSvc.UpdateProcessorAndReconReferenceByID(ctx, request.Transaction.UUID.String(), request.ProcessorReference, request.UUID, request.GetReconReferenceNo()); err != nil {
		return fmt.Errorf("update processor and recon reference id: %v", err)
	}

	bankTransferResponse := request.ToSnapBankTransferResponseData()

	var (
		status = constant.StatusSuccess
		// Only not null when the status is not SUCCESS
		reasonType, reasonDescription *string
	)
	if bankTransferResponse.Status != constant.SnapCoreBankTransferStatusSuccess {
		// Make memory allocations because the default value of the following variables is nil.
		reasonType, reasonDescription = util.ValueToPtr(""), util.ValueToPtr("")

		// Mapping transfer status to transaction status
		status, *reasonType, *reasonDescription = bankTransferResponse.MappingAccountTransactionErrStatus()
	}
	if err := s.orchestratorSvc.UpdateStatusAccountTransaction(ctx, request.Transaction.UUID.String(), status, reasonType, reasonDescription); err != nil {
		return fmt.Errorf("update transaction status: %v", err)
	}

	// Status is generated by mapping transfer status to transaction status.
	//
	// Only send callback for final withdrawal status (SUCCESS or FAILED) triggered via Open API.
	if withdrawalDetail.Metadata.Source != constant.SourceOpenApi || status == constant.StatusPending {
		return nil
	}

	callbackRequest := withdrawal.WithdrawalStatusCallbackRequest{
		ID:         withdrawalDetail.Id,
		MerchantId: withdrawalDetail.MerchantID,
		Withdrawal: withdrawal.OpenAPIWithdrawalDetailResponse{
			ReferenceID:  withdrawalDetail.ReferenceID,
			WithdrawType: withdrawalDetail.Metadata.WithdrawType,
			IsFullAmount: withdrawalDetail.Metadata.IsFullAmount,
			Amount: &commonModel.Amount{
				Currency: constant.CurrencyIDR,
				Value:    fmt.Sprintf("%.0f", withdrawalDetail.Amount),
			},
			Description: withdrawalDetail.Description,
		},
		Status:    status,
		CreatedAt: withdrawalDetail.CreatedAt.Format(time.RFC3339), UpdatedAt: updateAt.Format(time.RFC3339),
	}
	if err = s.SendWithdrawalStatusCallback(ctx, callbackRequest); err != nil {
		s.logger.Warn(ctx, "Failed to send withdrawal final status", logger.Error(err), logger.Any("callbackRequest", callbackRequest))
	}
	return nil
}
